-- Brand / mitra mengajukan kerja sama langsung dari halaman /program.
CREATE TABLE public.partnership_proposals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_name text NOT NULL,
  contact_name text NOT NULL,
  whatsapp text NOT NULL,
  email text NOT NULL,
  brand_category text NOT NULL,
  collaboration_types text NOT NULL,
  budget_range text,
  message text,
  status text NOT NULL DEFAULT 'diajukan',
  created_at timestamptz NOT NULL DEFAULT now()
);

GRANT INSERT ON public.partnership_proposals TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.partnership_proposals TO authenticated;
GRANT ALL ON public.partnership_proposals TO service_role;

ALTER TABLE public.partnership_proposals ENABLE ROW LEVEL SECURITY;

-- Pengisian publik divalidasi di sisi database, bukan hanya di formulir.
CREATE POLICY "Anyone can propose a partnership" ON public.partnership_proposals
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    char_length(btrim(brand_name)) BETWEEN 2 AND 120
    AND char_length(btrim(contact_name)) BETWEEN 2 AND 100
    AND char_length(email) <= 255
    AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    AND char_length(whatsapp) BETWEEN 9 AND 16
    AND whatsapp ~ '^[0-9+[:space:]-]+$'
    AND brand_category IN (
      'Kuliner & F&B', 'Kopi & Cafe', 'Fashion & Apparel', 'Kosmetik & Perawatan',
      'Ritel & UMKM', 'Teknologi & Aplikasi', 'Pendidikan & Sekolah',
      'Instansi & Pemerintah', 'Media & Televisi', 'Lainnya'
    )
    AND char_length(btrim(collaboration_types)) BETWEEN 2 AND 300
    AND NOT EXISTS (
      SELECT 1
      FROM unnest(string_to_array(collaboration_types, ',')) AS picked(item)
      WHERE btrim(picked.item) NOT IN (
        'Sponsorship acara', 'Sponsorship produk', 'Booth & stand',
        'Kerja sama konten', 'Media partner', 'Hadiah & doorprize', 'Lainnya'
      )
    )
    AND (budget_range IS NULL OR budget_range IN (
      'Belum ditentukan', 'Barter produk / jasa', 'Di bawah Rp 5 juta',
      'Rp 5 – 15 juta', 'Rp 15 – 30 juta', 'Di atas Rp 30 juta'
    ))
    AND char_length(coalesce(message, '')) <= 1500
    AND status = 'diajukan'
  );

CREATE POLICY "Admins manage partnership proposals" ON public.partnership_proposals
  FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin')) WITH CHECK (public.has_role(auth.uid(), 'admin'));
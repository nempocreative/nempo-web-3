#!/usr/bin/env bash
# Rebuilds the Garut Beans sub-site into public/garut-beans/.
# Usage: bash scripts/garut-beans/build.sh   (from the project root)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SRC="${GB_SRC:-/tmp/garut-beans}"
if [ ! -d "$SRC/.git" ]; then
  git clone --depth 1 https://github.com/nempocreative/Garut-Coffee-166 "$SRC"
fi
cd "$SRC"
pnpm install --filter "@workspace/kopi-garut-web..." --ignore-scripts --frozen-lockfile
APP="$SRC/artifacts/kopi-garut-web"
cp "$HERE/vite.nempo.config.ts" "$APP/vite.nempo.config.ts"
cd "$APP"
GB_APP_ROOT="$APP" GB_SHIMS="$HERE/shims" NODE_ENV=production npx vite build --config vite.nempo.config.ts
rm -rf "$ROOT/public/garut-beans"
cp -R "$APP/dist/nempo" "$ROOT/public/garut-beans"
# The original page hard-codes its Replit path in the loader image and a few CSS urls.
grep -rl "/kopi-garut-web/" "$ROOT/public/garut-beans" --include=*.html --include=*.css --include=*.js \
  | xargs -r sed -i "s#/kopi-garut-web/#/garut-beans/#g"
# Drop source images the built pages never reference (leftover drafts and PNG originals).
# Gift-box cut-outs are picked by product id at runtime, so they always stay.
python3 - "$ROOT/public/garut-beans" <<'PY'
import os, sys, glob
d = sys.argv[1]; a = os.path.join(d, 'assets')
text = open(os.path.join(d, 'index.html')).read()
for f in glob.glob(os.path.join(a, 'index-*')):
    text += open(f, errors='ignore').read()
removed = 0
for name in os.listdir(a):
    if name.startswith('index-') or name.startswith('gift-box-cutout-') or name in text:
        continue
    removed += os.path.getsize(os.path.join(a, name)); os.remove(os.path.join(a, name))
print(f"pruned {removed // 1048576} MB of unused images")
PY
# The page shell is served by src/routes/garut-beans*.tsx so deep links survive a refresh.
node -e '
const fs=require("fs");
const html=fs.readFileSync(process.argv[1],"utf8");
fs.writeFileSync(process.argv[2],"// Generated by scripts/garut-beans/build.sh — do not edit.\nexport const GARUT_BEANS_HTML = "+JSON.stringify(html)+";\n");
' "$ROOT/public/garut-beans/index.html" "$ROOT/src/lib/garut-beans-shell.ts"
echo "Garut Beans built into public/garut-beans"
